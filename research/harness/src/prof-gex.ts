import { readFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { parseCboeChain } from "@predictit/adapters";
import { contractGammas, gexSummary, impliedVol, bsGreeks, yearsToExpiry, expiryInstantMs } from "@predictit/engine";
const raw = JSON.parse(gunzipSync(readFileSync(process.argv[2]!)).toString("utf8"));
const chain = parseCboeChain(raw, Date.parse(raw._received_utc), { maxDays: 95, strikePct: 0.1 });
const asOf = chain.stamp.observedAt;
let t = performance.now();
for (let i = 0; i < 200000; i++) bsGreeks("C", { S: 7400, K: 7400 + (i % 50), T: 0.003, sigma: 0.2 });
console.log("200k bsGreeks ms", (performance.now() - t).toFixed(0));
t = performance.now();
for (let i = 0; i < 2000; i++) impliedVol("C", 25 + (i % 10), { S: 7400, K: 7400, T: 0.003 });
console.log("2k impliedVol ms", (performance.now() - t).toFixed(0));
t = performance.now();
for (let i = 0; i < 2000; i++) yearsToExpiry(asOf, expiryInstantMs("SPXW", "2026-11-13"));
console.log("2k yearsToExpiry+expiryInstant ms", (performance.now() - t).toFixed(0));
t = performance.now();
const cg = contractGammas(chain, asOf);
console.log("contractGammas ms", (performance.now() - t).toFixed(0), cg.length);
t = performance.now();
gexSummary(chain, asOf);
console.log("gexSummary total ms", (performance.now() - t).toFixed(0));
